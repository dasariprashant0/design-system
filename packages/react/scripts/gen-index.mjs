// Writes src/index.ts: one `export *` per component/hook folder. Run by build, test and typecheck.
// Never edit src/index.ts by hand; add a folder with an index.ts instead.
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pkgRoot, units} from './lib.mjs';

const lines = units().map((u) => `export * from './${u.kind}/${u.name}';`);
const out = `// GENERATED by scripts/gen-index.mjs. Do not edit.\n${lines.join('\n')}\nexport {cx} from './utils/cx';\nexport {styles} from './styles';\nexport type {ComponentMeta, Category} from './meta';\nexport type {Demo} from './demo';\n`;
writeFileSync(join(pkgRoot, 'src', 'index.ts'), out);
console.log(`src/index.ts: ${lines.length} exports`);

// styles.ts: component folder name -> the one @monoline/css bundle it needs (already includes the CSS of every part it uses).
// Import 'core' once, then the bundle of each component you use.
const styles = {core: '@monoline/css/core.css'};
for (const u of units().filter((x) => x.kind === 'components')) {
  const meta = JSON.parse(readFileSync(join(u.dir, 'meta.json'), 'utf8'));
  if (meta.css?.length) styles[u.name] = `@monoline/css/components/${u.name}.css`;
}
const entries = Object.entries(styles).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(join(pkgRoot, 'src', 'styles.ts'), `// GENERATED by scripts/gen-index.mjs. Do not edit.
/**
 * Where each component's stylesheet lives, by component folder name (kebab-case, as on the docs site). Import \`styles.core\` once, then one file per component you use, instead of the whole \`@monoline/css\`.
 * @example import '@monoline/css/core.css'; import '@monoline/css/components/button.css'; // same as styles.core and styles.button
 */
export const styles: Readonly<Record<string, string>> = {
${entries}
};
`);
console.log(`src/styles.ts: ${Object.keys(styles).length} entries`);
