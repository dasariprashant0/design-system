// Writes src/index.ts: one `export *` per component/hook folder. Run by build, test and typecheck.
// Never edit src/index.ts by hand; add a folder with an index.ts instead.
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pkgRoot, units} from './lib.mjs';

const lines = units().map((u) => `export * from './${u.kind}/${u.name}';`);
const out = `// GENERATED by scripts/gen-index.mjs. Do not edit.\n${lines.join('\n')}\nexport {cx} from './utils/cx';\nexport type {ComponentMeta, Category} from './meta';\nexport type {Demo} from './demo';\n`;
writeFileSync(join(pkgRoot, 'src', 'index.ts'), out);
console.log(`src/index.ts: ${lines.length} exports`);
