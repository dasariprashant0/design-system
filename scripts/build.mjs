// Builds the distributable files from css/. Run: npm run build. Commit the output.
//   css/monoline.css      all stylesheets as one (CDN link, npm main)
//   css/monoline.min.css  the same, minified
//   tokens/tokens.json    every token, in the W3C design-tokens shape, for Figma / Style Dictionary
import {mkdirSync, writeFileSync} from 'node:fs';
import {read, parseTokens, isColor} from './lib.mjs';

const pkg = JSON.parse(read('package.json'));
const parts = ['tokens', 'base', 'components', 'utilities', 'accents'];
const css = parts.map((p) => read(`css/${p}.css`)).join('\n');
const banner = `/* Monoline ${pkg.version} | MIT | tokens + base + components + utilities + accents. Generated by scripts/build.mjs; edit css/*.css instead. */\n`;
const min = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/\s*([{};])\s*/g, '$1').trim();

writeFileSync(new URL('../css/monoline.css', import.meta.url), banner + css);
writeFileSync(new URL('../css/monoline.min.css', import.meta.url), banner + min + '\n');

const {base, themes, accents} = parseTokens();
const tok = (v) => ({$value: v, ...(isColor(v) ? {$type: 'color'} : {})});
const map = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k.slice(2), tok(v)]));
const tokens = {
  $description: `Monoline ${pkg.version} design tokens, generated from css/tokens.css and css/accents.css.`,
  base: map(base),
  theme: Object.fromEntries(Object.entries(themes).map(([t, v]) => [t, map(v)])),
  accent: Object.fromEntries(Object.entries(accents).map(([a, byTheme]) => [a, Object.fromEntries(Object.entries(byTheme).map(([t, v]) => [t, map(v)]))])),
};
mkdirSync(new URL('../tokens/', import.meta.url), {recursive: true});
writeFileSync(new URL('../tokens/tokens.json', import.meta.url), JSON.stringify(tokens, null, 2) + '\n');
console.log(`built monoline.css ${(css.length / 1024).toFixed(1)} KB, min ${(min.length / 1024).toFixed(1)} KB, tokens.json`);
